import os
import sys

# Ensure local blindlog is in python path
sys.path.insert(0, r"c:\Users\akhand_admin\Downloads\blindlog\src")

import time
import json
from blindlog.core import BlindLogger

def stress_test():
    print("=== BlindLog v1.1 Stress & Integrity Test ===\n")
    
    # 1. Initialize Logger
    os.environ["BLINDLOG_SECRET"] = "enterprise-secure-key"
    logger = BlindLogger()
    
    # 2. Fast Path Test (Valid Schema)
    payload = {
        "status": "success",
        "user": {
            "email": "akhand@gmail.com",
            "metadata": "No sensitive key here, text might be scanned if implemented",
            "credit_card": "4111-2222-3333-4444"
        },
        # credentials should be safely blinded without being flattened to a string literal
        "credentials": { 
            "oauth_token": "ya29.a0AfH6...",
            "refresh_token": "1//0g..."
        }
    }
    
    # Add custom sensitive keys on the fly to test Registry configuration
    logger.config.sensitive_keys.add("credentials")
    logger.config.sensitive_keys.add("credit_card")
    
    print("[1] Testing Nested Transformation (Fast Path & Recursive Object Preservation):")
    start = time.time()
    masked_payload = logger.mask(payload)
    end = time.time()
    print(f"Execution Time: {(end - start)*1000:.3f} ms")
    print(f"Output: {json.dumps(masked_payload, indent=2)}\n")
    
    # 3. Slow Path Test (Embedded Context)
    print("[2] Testing Regex Slow Path (Embedded Context Processing):")
    text = "FATAL ERROR generated by user akhand@gmail.com. Last payment attempted on 4111-2222-3333-4444."
    start = time.time()
    masked_text = logger.mask(text)
    end = time.time()
    print(f"Execution Time: {(end - start)*1000:.3f} ms")
    print(f"Output: {masked_text}\n")
    
    # 4. ReDoS Boundary Test (100,000+ characters)
    print("[3] Testing ReDoS Defensive Boundary (100k Character Attack):")
    # Generating 1MB malicious string
    long_text = "a" * 1050000 
    start = time.time()
    masked_long = logger.mask(long_text)
    end = time.time()
    print(f"Execution Time: {(end - start)*1000:.3f} ms")
    print(f"Output: {masked_long[:50]}...\n")
    
    print("=== Test Suite Complete ===")

if __name__ == "__main__":
    stress_test()
